-- Run against the existing H2 database before starting with the default ddl-auto=validate profile.
-- Existing member_housing_roles rows have no contract or counterparty information and cannot be migrated.
CREATE TABLE IF NOT EXISTS housing_contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    landlord_member_id BIGINT NOT NULL,
    tenant_member_id BIGINT NOT NULL,
    CONSTRAINT fk_housing_contract_landlord FOREIGN KEY (landlord_member_id) REFERENCES members(id),
    CONSTRAINT fk_housing_contract_tenant FOREIGN KEY (tenant_member_id) REFERENCES members(id),
    CONSTRAINT ck_housing_contract_distinct_parties CHECK (landlord_member_id <> tenant_member_id)
);
