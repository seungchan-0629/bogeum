-- 기존 H2 DB의 members 테이블을 유지한 채 추가한다. 운영 DB가 바뀌면 해당 DB 문법으로 검토한다.
CREATE TABLE IF NOT EXISTS social_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    provider VARCHAR(20) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_social_member FOREIGN KEY (member_id) REFERENCES members(id),
    CONSTRAINT uk_social_provider_user UNIQUE (provider, provider_user_id),
    CONSTRAINT uk_social_member_provider UNIQUE (member_id, provider)
);
